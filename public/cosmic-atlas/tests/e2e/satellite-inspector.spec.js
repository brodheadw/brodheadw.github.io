import {test,expect} from '@playwright/test';
import fs from 'node:fs';

const historical=JSON.parse(fs.readFileSync(new URL('../unit/fixtures/skyfield-passes.json',import.meta.url)));

test('historical ISS fixture exercises the worker, inspector, ground track, Doppler and passes',async({page},testInfo)=>{
  testInfo.annotations.push({type:'fixture',description:'Historical 2019 ISS verification data; this is not a current public satellite catalog or a full-catalog performance test.'});
  const fulfill=(route,data)=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(data)});
  await page.route('**/data/satellites/status.json',route=>fulfill(route,{schema:1,available:true,suspended:false,fixture:true,error:null}));
  await page.route('**/data/satellites/gp.json',route=>fulfill(route,{schema:1,fetched_at:'2019-12-09T16:38:29Z',coverage:'HISTORICAL VERIFICATION FIXTURE',source:historical.tleSource,objects:[historical.omm]}));
  await page.route('**/data/satellites/satcat.json',route=>fulfill(route,{schema:1,fetched_at:'2019-12-09T16:38:29Z',objects:[{NORAD_CAT_ID:25544,OBJECT_TYPE:'PAY',OWNER:'ISS',LAUNCH_DATE:'1998-11-20'}]}));
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>window.__atlas?.ready);
  await expect(page.locator('#sceneError')).toBeHidden();
  await page.evaluate(async()=>{await Promise.all(['data/textures/earth-day.jpg','data/textures/earth-night.jpg'].map(async url=>{const image=new Image();image.src=url;await image.decode();}));});
  if(await page.locator('#about').evaluate(dialog=>dialog.open))await page.locator('#aboutExplore').click();
  await page.evaluate(utc=>window.__atlas.store.set({clock:{utc,rate:1,paused:false}}),historical.cases[0].lookUtc);
  await page.selectOption('#workspace','earth');
  await page.waitForFunction(()=>window.__atlas.satellites.length===1&&window.__atlas.satelliteState?.valid[0]);
  await page.getByRole('searchbox',{name:'Search satellites'}).fill('25544');
  await page.locator('button[data-satellite]').filter({hasText:'ISS (ZARYA)'}).click();
  const inspector=page.locator('#panels [data-panel="inspector"]');
  await inspector.evaluate(panel=>{panel.open=true;});
  await expect(inspector.locator('.inspector-title')).toHaveText('ISS (ZARYA)');
  await expect(inspector).toContainText('Geodetic altitude');
  await expect(inspector).toContainText('GCRS approximate (IAU2000B)');
  await expect(inspector.locator('[data-track] svg')).toHaveCount(1);
  const first=await page.evaluate(()=>window.__atlas.selectedDetails());
  expect(first.altitudeKm).toBeGreaterThan(350);expect(first.altitudeKm).toBeLessThan(450);
  expect(first.speedKmS).toBeGreaterThan(7.4);expect(first.speedKmS).toBeLessThan(7.9);
  await inspector.locator('[data-window]').selectOption('2');
  await inspector.locator('[data-frequency]').fill('437.5');
  await expect(inspector.locator('[data-doppler]')).toContainText('MHz');
  await page.waitForTimeout(1300);
  await expect(inspector.locator('[data-window]')).toHaveValue('2');
  await expect(inspector.locator('[data-frequency]')).toHaveValue('437.5');
  const second=await page.evaluate(()=>window.__atlas.selectedDetails());
  expect(second.temePosition).not.toEqual(first.temePosition);
  const downloadPromise=page.waitForEvent('download');await inspector.locator('[data-json]').click();
  const download=await downloadPromise;expect(download.suggestedFilename()).toBe('25544-state.json');
  const passes=page.locator('#panels [data-panel="passes"]');
  await passes.evaluate(panel=>{panel.open=true;});
  await passes.locator('[data-passes]').click();
  await expect(passes.locator('[data-out]')).toContainText('Culmination');
  await inspector.locator('[data-window]').scrollIntoViewIfNeeded();
  // Live updates were verified above; freeze this historical instant for a settled screenshot.
  await page.evaluate(()=>{const atlas=window.__atlas;atlas.store.set({clock:{...atlas.snapshotState().clock,paused:true}});});
  await page.waitForFunction(()=>{
    const atlas=window.__atlas,state=atlas.store.getState(),rig=atlas.renderer.getRig(),earth=atlas.bodies.find(body=>body.id==='earth'),positions=atlas.satelliteState?.gcrsPositions;
    if(!earth||!positions||state.selection?.layer!=='satellites')return false;
    const index=state.selection.index,mpcKm=3.0856775814913673e19;
    const expected=[0,1,2].map(k=>(earth.position[k]+positions[index*3+k])/mpcKm);
    const stateErrorKm=Math.hypot(...expected.map((value,k)=>(value-state.camera.target[k])*mpcKm));
    const rigError=Math.hypot(...rig.target.map((value,k)=>value-state.camera.target[k]))/state.camera.distance;
    return stateErrorKm<30&&rigError<1e-5&&Math.abs(rig.distance/state.camera.distance-1)<1e-5;
  });
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  await page.screenshot({path:testInfo.outputPath('historical-iss-inspector.png'),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1)).toBe(false);
  expect(errors).toEqual([]);
});

test('satellite snapshot refresh preserves NORAD selection and leaves removed objects unselected',async({page},testInfo)=>{
  testInfo.annotations.push({type:'fixture',description:'Historical ISS plus a synthetic identity-only row test snapshot refresh; no provider requests or current-catalog claims.'});
  const second={...historical.omm,NORAD_CAT_ID:43210,OBJECT_NAME:'SYNTHETIC IDENTITY TEST'};
  let objects=[historical.omm,second],gpRequests=0;
  const fulfill=(route,data)=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(data)});
  const registry=JSON.parse(fs.readFileSync(new URL('../../data/layers.json',import.meta.url)));
  registry.layers.find(layer=>layer.id==='satellites').files.json='data/satellites/gp.json';
  await page.route('**/data/layers.json',route=>fulfill(route,registry));
  await page.route('**/data/satellites/status.json',route=>fulfill(route,{schema:1,available:true,fixture:true}));
  await page.route('**/data/satellites/gp.json',route=>{gpRequests++;return fulfill(route,{schema:1,fetched_at:'2019-12-09T16:38:29Z',coverage:'HISTORICAL IDENTITY TEST',source:historical.tleSource,objects});});
  await page.route('**/data/satellites/satcat.json',route=>fulfill(route,{schema:1,objects:[]}));
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>window.__atlas?.ready);
  expect(gpRequests).toBe(0);
  expect(await page.evaluate(()=>window.__atlas.satellites.length)).toBe(0);
  if(await page.locator('#about').evaluate(dialog=>dialog.open))await page.locator('#aboutExplore').click();
  await page.evaluate(utc=>{const a=window.__atlas;a.workspace('earth');a.store.set({clock:{utc,rate:1,paused:true},selection:{layer:'satellites',id:0}});},historical.cases[0].lookUtc);
  await page.waitForFunction(()=>window.__atlas.satellites.length===2&&window.__atlas.satelliteState?.valid[0]);
  expect(gpRequests).toBe(1);
  await page.evaluate(()=>window.__atlas.select('satellites',0));
  expect(await page.evaluate(()=>window.__atlas.store.getState().selection)).toEqual({layer:'satellites',id:'sat:25544',index:0});
  const inspector=page.locator('#panels [data-panel="inspector"]');
  await inspector.evaluate(panel=>{panel.open=true;});
  await expect(inspector.locator('.inspector-title')).toHaveText('ISS (ZARYA)');
  const saved=await page.evaluate(async()=>{const {exportPreset}=await import('/js/presets.js');return exportPreset(window.__atlas.snapshotState());});
  objects=[second,historical.omm];
  await page.evaluate(()=>window.__atlas.syncCatalogs());
  await page.waitForFunction(()=>window.__atlas.satelliteState?.valid[1]);
  expect(await page.evaluate(()=>window.__atlas.status.get('satellites').error)).toBeUndefined();
  expect(await page.evaluate(()=>window.__atlas.store.getState().selection)).toEqual({layer:'satellites',id:'sat:25544',index:1});
  expect(await page.evaluate(()=>window.__atlas.selectionRow().norad)).toBe(25544);
  expect((await page.evaluate(()=>window.__atlas.selectedDetails())).norad).toBe(25544);
  await inspector.locator('[data-follow]').click();
  await inspector.locator('[data-follow]').click();
  expect(await page.evaluate(()=>window.__atlas.store.getState().selection.id)).toBe('sat:25544');
  await page.evaluate(async text=>{const {importPreset}=await import('/js/presets.js');window.__atlas.store.replace((await importPreset(text)).state);},saved);
  expect(await page.evaluate(()=>window.__atlas.store.getState().selection.index)).toBe(1);
  objects=[second];
  await page.evaluate(()=>window.__atlas.syncCatalogs());
  expect(await page.evaluate(()=>window.__atlas.store.getState().selection)).toEqual({layer:'satellites',id:'sat:25544',index:-1});
  expect(await page.evaluate(()=>window.__atlas.store.getState().camera.mode)).toBe('orbit');
  expect(await page.evaluate(()=>window.__atlas.selectionRow())).toBeNull();
  expect(await page.evaluate(()=>window.__atlas.selectedDetails())).toBeNull();
  await expect(inspector).toContainText('Selected NORAD 25544 is absent from this snapshot.');
  expect(errors).toEqual([]);
});
