  const messages = []; errors.set(page, messages)
  page.on('pageerror', error => messages.push(error.message))
  page.on('console', message => { if (message.type() === 'error') messages.push(message.text()) })
  await page.route('https://raw.githubusercontent.com/brodheadw/brodheadw.github.io/satellite-data/data/weather/status.json', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ schema: 1, available: false, error: 'Use the bundled dated observations for browser verification.' }) }))
