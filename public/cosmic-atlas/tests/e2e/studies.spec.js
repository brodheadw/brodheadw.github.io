async function savedDownload(page, locator, outputPath) {
  const pending = page.waitForEvent('download'); await locator.click()
  const download = await pending; await download.saveAs(outputPath)
  return JSON.parse(await fs.readFile(outputPath, 'utf8'))
}

test('joint sky scans save and export reproducible results and compare in the notebook', async ({ page }, testInfo) => {
  await openAtlas(page)
  const panel = page.locator('[data-panel="laboratory"]'); await panel.evaluate(el => { el.open = true })
  await panel.locator('[data-radii]').fill('1, 2')
  await panel.locator('[data-cuts]').fill('0, 300000')
  await panel.locator('[data-scrambles]').fill('39')
  await panel.locator('[data-seed]').fill('7')
  await panel.locator('[data-run]').click()
  const out = panel.locator('[data-output]')
  await expect(out).toContainText('GLOBAL GRID p')
  await out.locator('[data-name]').fill('Seed seven sky scan')
  await out.locator('[data-save]').click()
  const first = await page.evaluate(() => window.__atlas.store.getState().experiments.find(run => run.method === 'sky-parameter-scan'))
  expect(first.cells).toHaveLength(4)
  expect(first.inputs.seed).toBe(7)
  expect(first.pResolution).toBe(1 / 40)
  expect(first.globalP).toBeGreaterThanOrEqual(first.pResolution)
  expect(first.cells.every(cell => cell.expected === cell.expectedRA && cell.globalP >= cell.localP)).toBe(true)
  const exported = await savedDownload(page, out.locator('[data-json]'), testInfo.outputPath('sky-parameter-scan.json'))
  expect(exported.inputs.inputFingerprint).toBe(first.inputs.inputFingerprint)
  expect(exported.scrambleMaxima).toEqual(first.scrambleMaxima)
  await panel.locator('[data-seed]').fill('9'); await panel.locator('[data-run]').click()
  await expect(out).toContainText('GLOBAL GRID p')
  await out.locator('[data-name]').fill('Seed nine sky scan'); await out.locator('[data-save]').click()
  const runs = await page.evaluate(() => window.__atlas.store.getState().experiments.filter(run => run.method === 'sky-parameter-scan'))
  expect(runs).toHaveLength(2)
  expect(runs[0].cells.map(cell => cell.expected)).toEqual(runs[1].cells.map(cell => cell.expected))
  const notebook = panel.locator('[data-history]'); await notebook.locator(':scope > details').evaluate(el => { el.open = true })
  await notebook.locator('[data-choose="0"]').check(); await notebook.locator('[data-choose="1"]').check()
  await notebook.locator('[data-compare]').click()
  await expect(notebook.locator('[data-comparison]')).toContainText('Seed seven sky scan')
  await expect(notebook.locator('[data-comparison]')).toContainText('Seed nine sky scan')
  const saved = await savedDownload(page, notebook.locator('[data-export]'), testInfo.outputPath('saved-notebook.json'))
  expect(saved.studies).toHaveLength(2)
  await out.scrollIntoViewIfNeeded(); await page.screenshot({ path: testInfo.outputPath('sky-study-notebook.png'), fullPage: true })
})

