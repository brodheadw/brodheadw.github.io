test('a labelled historical OMM file imports through the chooser and powers a saved observer pass study', async ({ page }, testInfo) => {
  testInfo.annotations.push({ type: 'fixture', description: 'User-file workflow verified with the historical 2019 ISS OMM fixture. No current feed, provider request or full-catalog throughput claim.' })
  let gpRequests = 0
  await page.route('**/data/satellites/status.json', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ schema: 1, available: false, error: 'Published feed disabled for local-file verification.' }) }))
  await page.route('**/gp.json', route => { gpRequests++; return route.fulfill({ status: 503, body: 'No GP requests are part of this verification.' }) })
  await openAtlas(page); await page.selectOption('#workspace', 'earth')
  const source = page.locator('[data-panel="satellite-data"]'); await source.evaluate(el => { el.open = true })
  const chooserPromise = page.waitForEvent('filechooser'); await source.locator('[data-import]').click()
  await (await chooserPromise).setFiles({ name: 'HISTORICAL-2019-ISS-VERIFICATION.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ objects: [historical.omm], source: 'Historical verification fixture; not a current public catalog' })) })
  await page.waitForFunction(() => window.__atlas.satellites.length === 1 && window.__atlas.satelliteSnapshot?.imported)
  await expect(source).toContainText('HISTORICAL-2019-ISS-VERIFICATION.json')
  await source.locator('[data-epoch]').click()
  await page.waitForFunction(() => window.__atlas.satelliteState?.valid[0])
  await page.getByRole('searchbox', { name: 'Search satellites' }).fill('25544')
  await page.locator('button[data-satellite]').filter({ hasText: 'ISS (ZARYA)' }).click()
  await expect.poll(() => page.evaluate(() => window.__atlas.store.getState().selection.id)).toBe('sat:25544')
  const panel = page.locator('[data-panel="orbit-study"]'); await panel.evaluate(el => { el.open = true })
  await panel.locator('[data-mode]').selectOption('passes')
  await panel.locator('[data-hours]').selectOption('24')
  await panel.locator('[data-starts]').fill('0')
  await panel.locator('[data-observers]').fill('40,-74,0\n51.5,-0.1,0')
  await panel.locator('[data-run]').click()
  const out = panel.locator('[data-output]'); await expect(out).toContainText('Run 1')
  await out.locator('[data-name]').fill('Historical ISS two-observer passes'); await out.locator('[data-save]').click()
  const exported = await savedDownload(page, out.locator('[data-json]'), testInfo.outputPath('historical-observer-pass-study.json'))
  expect(exported.method).toBe('orbital-study')
  expect(exported.runs).toHaveLength(2)
  expect(exported.summary.passCount).toBeGreaterThan(0)
  expect(exported.summary.visibilitySampleCount).toBeGreaterThan(0)
  expect(exported.inputs.snapshot.imported.filename).toBe('HISTORICAL-2019-ISS-VERIFICATION.json')
  expect(exported.inputs.seedUsed).toBe(false)
  expect(exported.assumptions.join(' ')).toContain('not official conjunction assessments')
  const savedCount = await page.evaluate(() => window.__atlas.store.getState().experiments.length)
  await page.evaluate(() => {
    const client = window.__atlas.client; window.__originalStudyRequest = client.request
    client.request = (method, args) => method === 'passes' ? new Promise(resolve => { window.__releaseStudy = () => resolve({ passes: [], method: 'delayed response after cancellation' }) }) : window.__originalStudyRequest(method, args)
  })
  await panel.locator('[data-run]').click(); await page.waitForFunction(() => typeof window.__releaseStudy === 'function')
  const replacementChooser = page.waitForEvent('filechooser'); await source.locator('[data-import]').click()
  await (await replacementChooser).setFiles({ name: 'HISTORICAL-2019-ISS-REPLACEMENT.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ objects: [historical.omm], source: 'Replacement historical verification file' })) })
  await expect(out).toContainText('Study cancelled')
  await expect(out.locator('[data-save]')).toHaveCount(0)
  expect(await page.evaluate(() => window.__atlas.store.getState().experiments.length)).toBe(savedCount)
  await page.evaluate(() => { window.__releaseStudy(); window.__atlas.client.request = window.__originalStudyRequest })
  await expect(out).toContainText('Study cancelled')
  expect(gpRequests).toBe(0)
})

test('dated Earth cloud observations are opt-in and independent of the simulation clock', async ({ page }, testInfo) => {
  await page.route('**/data/satellites/status.json', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ schema: 1, available: false, error: 'Satellite feed disabled for independent weather verification.' }) }))
  await openAtlas(page); await pauseClock(page)
  await page.evaluate(() => {
    const renderer = window.__atlas.renderer.renderer, render = renderer.render
    renderer.render = function (scene, camera) {
      scene.traverse(mesh => { if (mesh.userData.bodyId === 'earth' && mesh.material.uniforms?.weatherOpacity) window.__weatherDisplay = { opacity: mesh.material.uniforms.weatherOpacity.value, width: mesh.material.uniforms.weather.value.image?.width || 0 } })
      return render.call(this, scene, camera)
    }
  })
  await page.selectOption('#workspace', 'earth')
  const panel = page.locator('[data-panel="earth-weather"]'); await panel.evaluate(el => { el.open = true })
  await expect(panel.locator('[data-show]')).not.toBeChecked()
  await panel.locator('[data-show]').check()
  await page.waitForFunction(() => window.__atlas.weatherStatus?.available && window.__weatherDisplay?.opacity === .65 && window.__weatherDisplay.width > 1)
  const observation = await page.evaluate(() => window.__atlas.weatherStatus.observation_date)
  await expect(panel.locator('[data-status]')).toContainText(observation)
  await expect(panel.locator('img.weather-legend')).toBeVisible()
  await expect(panel).toContainText('not a forecast')
  await panel.locator('[data-opacity]').evaluate(input => { input.value = '.35'; input.dispatchEvent(new Event('input', { bubbles: true })) })
  await page.waitForFunction(() => window.__weatherDisplay?.opacity === .35)
  await page.screenshot({ path: testInfo.outputPath('earth-observed-clouds.png'), fullPage: true })
  await page.evaluate(() => window.__atlas.store.set({ clock: { utc: '2027-11-12T12:00:00Z', rate: 1, paused: true } }))
  expect(await page.evaluate(() => window.__atlas.weatherStatus.observation_date)).toBe(observation)
  await expect(panel.locator('[data-status]')).toContainText(observation)
  await panel.locator('[data-show]').uncheck()
  await page.waitForFunction(() => window.__weatherDisplay?.opacity === 0)
})

test('saved local-source identity and a late published response cannot replace the chosen OMM file', async ({ page }, testInfo) => {
  testInfo.annotations.push({ type: 'fixture', description: 'Historical ISS and a synthetic identity-only row verify source transactions. All published responses are intercepted; no external catalog requests or current-feed claims.' })
  let available = true, gpStarted = 0, releaseGP
  const other = { ...historical.omm, NORAD_CAT_ID: 43210, OBJECT_NAME: 'SYNTHETIC IDENTITY-ONLY ROW' }
  await page.route('**/data/satellites/status.json', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ schema: 1, available, error: available ? null : 'Published source unavailable in rollback verification.' }) }))
  await page.route('**/gp.json', async route => {
    gpStarted++; await new Promise(resolve => { releaseGP = resolve })
    await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ schema: 1, fetched_at: '2019-12-09T00:00:00Z', objects: [other], source: 'Intercepted historical identity fixture' }) }).catch(() => {})
  })
  await openAtlas(page); await page.selectOption('#workspace', 'earth')
  const source = page.locator('[data-panel="satellite-data"]'); await source.evaluate(el => { el.open = true })
  const importFile = async (name, objects) => {
    const pending = page.waitForEvent('filechooser'); await source.locator('[data-import]').click()
    await (await pending).setFiles({ name, mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ objects, source: 'Historical source-identity verification only' })) })
    await page.waitForFunction(name => window.__atlas.satelliteSnapshot?.imported?.filename === name, name)
  }
  try {
    await expect.poll(() => gpStarted).toBe(1)
    await importFile('HISTORICAL-SOURCE-A.json', [historical.omm])
    await source.locator('[data-epoch]').click(); await page.waitForFunction(() => window.__atlas.satelliteState?.valid[0])
    const savedA = await page.evaluate(() => window.__atlas.snapshotState())
    releaseGP(); await page.waitForTimeout(150)
    expect(await page.evaluate(() => window.__atlas.satellites.map(object => object.norad))).toEqual([25544])
    expect(await page.evaluate(() => window.__atlas.satelliteSnapshot.imported.filename)).toBe('HISTORICAL-SOURCE-A.json')
    await importFile('HISTORICAL-SOURCE-B.json', [other])
    await page.evaluate(state => window.__atlas.store.replace(state), savedA)
    await page.waitForFunction(() => window.__atlas.satellites.length === 0 && window.__atlas.satelliteSnapshot === null)
    await expect(source).toContainText(/re-import/i)
    await importFile('HISTORICAL-SOURCE-A.json', [historical.omm])
    expect(await page.evaluate(() => window.__atlas.store.getState().satelliteSource.sha256)).toBe(savedA.satelliteSource.sha256)
    available = false
    await source.locator('[data-published]').click()
    await expect(source.locator('[data-feedback]')).toContainText('Published source unavailable')
    expect(await page.evaluate(() => window.__atlas.satellites.map(object => object.norad))).toEqual([25544])
    expect(await page.evaluate(() => window.__atlas.store.getState().satelliteSource.kind)).toBe('local')
    await source.locator('[data-epoch]').click()
    await expect.poll(() => page.evaluate(async () => (await window.__atlas.selectedDetails())?.norad)).toBe(25544)
    expect(gpStarted).toBe(1)
  } finally { releaseGP?.() }
})

test('weather refresh versions its image and a failed new image retains the prior observation date', async ({ page }, testInfo) => {
  testInfo.annotations.push({ type: 'fixture', description: 'Synthetic version metadata and one intentionally invalid image verify cache and failure handling; raster bytes otherwise use the bundled dated NASA product.' })
  const base = JSON.parse(await fs.readFile(new URL('../../data/weather/status.json', import.meta.url)))
  let version = 0
  const imageRequests = []
  await page.route('**/data/satellites/status.json', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ schema: 1, available: false, error: 'Satellite feed disabled in weather refresh verification.' }) }))
  await page.route(url => url.hostname === '127.0.0.1' && url.pathname === '/data/weather/status.json', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ ...base, ...(version ? { sha256: `browser-refresh-v${version}`, observation_date: `2026-11-${11 + version}`, observation_end: `2026-11-${12 + version}T00:00:00Z` } : {}) }) }))
  page.on('request', request => { if (new URL(request.url()).pathname.endsWith('/weather/clouds.png')) imageRequests.push(request.url()) })
  await page.route(url => url.pathname.endsWith('/weather/clouds.png') && url.searchParams.get('atlas_version') === 'browser-refresh-v2', route => route.fulfill({ status: 200, contentType: 'image/png', body: Buffer.from('intentionally invalid image for the failure test') }))
  await openAtlas(page); await pauseClock(page)
  await page.evaluate(() => {
    const renderer = window.__atlas.renderer.renderer, render = renderer.render
    renderer.render = function (scene, camera) {
      scene.traverse(mesh => { if (mesh.userData.bodyId === 'earth' && mesh.material.uniforms?.weatherOpacity) window.__weatherOpacity = mesh.material.uniforms.weatherOpacity.value })
      return render.call(this, scene, camera)
    }
  })
  await page.selectOption('#workspace', 'earth')
  const panel = page.locator('[data-panel="earth-weather"]'); await panel.evaluate(el => { el.open = true })
  await panel.locator('[data-show]').check(); await page.waitForFunction(() => window.__atlas.weatherStatus?.available && window.__weatherOpacity > 0)
  version = 1; await panel.locator('[data-refresh]').click()
  await page.waitForFunction(() => window.__atlas.weatherStatus?.sha256 === 'browser-refresh-v1')
  expect(imageRequests.some(url => url.includes('atlas_version=browser-refresh-v1'))).toBe(true)
  const priorDate = await page.evaluate(() => window.__atlas.weatherStatus.observation_date)
  version = 2; await panel.locator('[data-refresh]').click()
  await page.waitForFunction(() => window.__atlas.weatherStatus?.error && window.__weatherOpacity === 0)
  expect(imageRequests.some(url => url.includes('atlas_version=browser-refresh-v2'))).toBe(true)
  expect(await page.evaluate(() => window.__atlas.weatherStatus.observation_date)).toBe(priorDate)
  await expect(panel.locator('[data-status]')).toContainText(priorDate)
})
